-- Drop all tables so this file can be re-run
DROP TABLE IF EXISTS Course_Prerequisite, Student_Major, Major_Course_Offering,
    AP_Credit, Transfer_Course, Waitlist, Enrollment, Section,
    Major, Instructor, Course, Student CASCADE;

-- Student: one row per student
CREATE TABLE Student (
    student_id    INT PRIMARY KEY, -- unique ID for each student
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    address       VARCHAR(200),
    phone_number  VARCHAR(20),
    email         VARCHAR(100) NOT NULL UNIQUE -- no two students can share an email
);

-- Course: the class in general, e.g. CS157A
CREATE TABLE Course (
    course_id   VARCHAR(10) PRIMARY KEY, -- course code (ex. CS157A)
    name        VARCHAR(100) NOT NULL,
    units       INT NOT NULL CHECK (units BETWEEN 1 AND 6), -- a course is worth 1 to 6 units
    department  VARCHAR(50) NOT NULL
);

-- Instructor: teaches sections
CREATE TABLE Instructor (
    instructor_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- ID is auto-filled if left out
    first_name     VARCHAR(50)  NOT NULL,
    last_name      VARCHAR(50)  NOT NULL,
    email          VARCHAR(100) NOT NULL UNIQUE
);

-- Major: e.g. Computer Science
CREATE TABLE Major (
    major_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100) NOT NULL UNIQUE
);

-- Section: one offering of a course (weak entity owned by Course)
CREATE TABLE Section (
    course_id          VARCHAR(10) NOT NULL,
    section_no         INT NOT NULL, -- section number (ex. 7 for Sec 07)
    name               VARCHAR(100), -- term name (ex. Fall 2026)
    start_date         DATE NOT NULL,
    end_date           DATE NOT NULL,
    capacity           INT NOT NULL CHECK (capacity >= 0), -- max number of enrolled students
    waitlist_capacity  INT NOT NULL DEFAULT 0 CHECK (waitlist_capacity >= 0),
	days               VARCHAR(7) NOT NULL -- meeting days (R = Thursday)
                       CHECK (days ~ '^M?T?W?R?F?S?$' AND days <> ''), -- only valid day letters in week order (assumes Sunday is not an option)
    start_time         TIME,
    end_time           TIME,
    location           VARCHAR(50),
    instructor_id      INT, -- can be NULL while the instructor is TBA
    PRIMARY KEY (course_id, section_no), -- weak entity: key borrows course_id from Course
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE CASCADE, -- if course is deleted, its sections go too
    FOREIGN KEY (instructor_id) REFERENCES Instructor(instructor_id) ON DELETE SET NULL, -- if instructor is deleted, section goes back to TBA
    CHECK (end_date >= start_date), -- term can't end before it starts
    CHECK (end_time > start_time) -- class can't end before it starts
);

-- Enrollment: one student enrolled in one section
CREATE TABLE Enrollment (
    enrollment_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     INT NOT NULL,
    course_id      VARCHAR(10) NOT NULL,
    section_no     INT NOT NULL,
    status         VARCHAR(10) NOT NULL DEFAULT 'enrolled' -- new enrollments start as 'enrolled'
                   CHECK (status IN ('enrolled', 'dropped', 'completed')),
    grade          VARCHAR(2) -- NULL until the course is completed
                   CHECK (grade IN ('A+','A','A-','B+','B','B-','C+','C','C-','D+','D','D-','F')),
    time_enrolled  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, -- filled in automatically with the current time
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id, section_no) REFERENCES Section(course_id, section_no) ON DELETE CASCADE,
    UNIQUE (student_id, course_id, section_no), -- can't enroll in the same section twice
    CHECK (grade IS NULL OR status = 'completed') -- only completed enrollments get a grade
);

-- Waitlist: one student waiting for a seat in one section
CREATE TABLE Waitlist (
    waitlist_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   INT NOT NULL,
    course_id    VARCHAR(10) NOT NULL,
    section_no   INT NOT NULL,
    position     INT NOT NULL CHECK (position >= 1), -- place in line, 1 = next to get a seat
    join_date    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id, section_no) REFERENCES Section(course_id, section_no) ON DELETE CASCADE,
    UNIQUE (student_id, course_id, section_no), -- on a section's waitlist only once
    UNIQUE (course_id, section_no, position) -- no two students share the same spot
);

-- Transfer_Course: a class from another school that counts for a course here
CREATE TABLE Transfer_Course (
    transfer_credit_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade               VARCHAR(2) NOT NULL
                        CHECK (grade IN ('A+','A','A-','B+','B','B-','C+','C','C-','D+','D','D-','F')),
    student_id          INT NOT NULL,
    course_id           VARCHAR(10), -- course this credit counts for; NULL if that course is deleted
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE SET NULL
);

-- AP_Credit: an AP exam score that counts for a course here
CREATE TABLE AP_Credit (
    transfer_credit_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score               INT NOT NULL CHECK (score BETWEEN 1 AND 5), -- AP scores are 1 to 5
    student_id          INT NOT NULL,
    course_id           VARCHAR(10), -- course this credit counts for; NULL if that course is deleted
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE SET NULL
);

-- Major_Course_Offering: which courses belong to which majors
CREATE TABLE Major_Course_Offering (
    major_id   INT NOT NULL,
    course_id  VARCHAR(10) NOT NULL,
    PRIMARY KEY (major_id, course_id),
    FOREIGN KEY (major_id) REFERENCES Major(major_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE CASCADE
);

-- Student_Major: which majors each student is in
CREATE TABLE Student_Major (
    student_id  INT NOT NULL,
    major_id    INT NOT NULL,
    PRIMARY KEY (student_id, major_id),
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (major_id) REFERENCES Major(major_id) ON DELETE RESTRICT -- can't delete a major that still has students
);

-- Course_Prerequisite: a course that requires another course (recursive)
CREATE TABLE Course_Prerequisite (
    course_id         VARCHAR(10) NOT NULL, -- the course that has the requirement
    prereq_course_id  VARCHAR(10) NOT NULL, -- the course you have to take first
    min_grade         VARCHAR(2) NOT NULL DEFAULT 'C-' -- lowest grade that still counts
                      CHECK (min_grade IN ('A+','A','A-','B+','B','B-','C+','C','C-','D+','D','D-')),
    override          BOOLEAN NOT NULL DEFAULT FALSE, -- TRUE if the requirement can be waived
    PRIMARY KEY (course_id, prereq_course_id),
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE CASCADE,
    FOREIGN KEY (prereq_course_id) REFERENCES Course(course_id) ON DELETE RESTRICT, -- can't delete a course others still require
    CHECK (course_id <> prereq_course_id) -- a course can't require itself
);
