-- Entities : STUDENT, COURSE, INSTRUCTOR, MAJOR
-- Weak entities:
--     SECTION       (owned by COURSE;  key = course_id + term + section_no)
--     UNIT_OVERRIDE (owned by STUDENT; key = student_id + term)
-- Students to sections:
--     ENROLLMENT  : a student taking a section
--     WAITLIST    : a student waiting for a seat in a section
-- ISA hierarchy:
--     TRANSFER_CREDIT -> TRANSFER_COURSE, AP_CREDIT
--     (the parent TRANSFER_CREDIT has no table of its own)
-- Many-to-many junction tables:
--     MAJOR_COURSE_OFFERING : which courses belong to which majors
--     STUDENT_MAJOR         : which majors each student is in
-- Recursive relationship:
--     COURSE_PREREQUISITE : a course that requires another course
-- ============================================================
 
-- Drop everything first so this file can be run again from scratch
-- CASCADE also drops the view that depends on these tables
DROP TABLE IF EXISTS Course_Prerequisite, Student_Major, Major_Course_Offering,
    AP_Credit, Transfer_Course, Waitlist, Enrollment, Unit_Override, Section,
    Major, Instructor, Course, Student CASCADE;
 
-- ------------------------------------------------------------
-- STUDENT
--   One row per student
--   student_id   : the student's ID number (primary key)
--   first_name   : the student's first name
--   last_name    : the student's last name
--   address      : home address (optional)
--   phone_number : phone number (optional)
--   email        : school email (UNIQUE: no two students can have the same one)
-- ------------------------------------------------------------
CREATE TABLE Student (
    student_id    INT PRIMARY KEY,
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    address       VARCHAR(200),
    phone_number  VARCHAR(20),
    email         VARCHAR(100) NOT NULL UNIQUE -- Alternate Key
);
 
-- ------------------------------------------------------------
-- COURSE
--   The class in general (has no specific time slot)
--   course_id  : the course code (formatted like 'CS157A') (primary key)
--   name       : full course title
--   units      : how many units the course is worth (1 to 6)
--   department : the department that offers it
-- ------------------------------------------------------------
CREATE TABLE Course (
    course_id   VARCHAR(10) PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    units       INT NOT NULL CHECK (units BETWEEN 1 AND 6),
    department  VARCHAR(50) NOT NULL
);
 
-- ------------------------------------------------------------
-- INSTRUCTOR
--   One row per instructor
--   instructor_id : the instructor's ID (primary key); filled in automatically
--   first_name    : the instructor's first name
--   last_name     : the instructor's last name
--   email         : school email (UNIQUE: no two instructors can have the same one)
-- ------------------------------------------------------------
CREATE TABLE Instructor (
    instructor_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name     VARCHAR(50)  NOT NULL,
    last_name      VARCHAR(50)  NOT NULL,
    email          VARCHAR(100) NOT NULL UNIQUE -- Alternate Key
);
 
-- ------------------------------------------------------------
-- UNIT_OVERRIDE: weak entity (owned by STUDENT)
--   An approved exception to the normal 18-unit limit for a student in one term
--   (example: student A may take 21 units in Fall 2026)
--   No row = the normal 18-unit limit applies
--   student_id    : the student who got the override
--   term          : the term it applies to like 'Fall 2026'
--                   (student_id + term) is the key, so a student can have
--                   at most one override per term
--   max_units     : the student's limit for that term; it can be higher
--                   than 18 (overload) or lower (academic probation)
--   approver_name : who approved it (advisor, chair, or dean)
--   approver_role : their role WHEN they approved it, so the record stays
--                   correct even if that person's role changes later
--   approved_date : the date it was approved
--   The unit limit trigger (trg_enrollment_units) reads this table
--   ON DELETE: student deleted -> their overrides are deleted (CASCADE)
-- ------------------------------------------------------------
CREATE TABLE Unit_Override (
    student_id     INT NOT NULL,
    term           VARCHAR(100) NOT NULL,
    max_units      INT NOT NULL CHECK (max_units BETWEEN 1 AND 21),
    approver_name  VARCHAR(100) NOT NULL,
    approver_role  VARCHAR(20) NOT NULL
                   CHECK (approver_role IN ('Instructor', 'Advisor', 'Department Chair', 'Dean')),
    approved_date  DATE NOT NULL DEFAULT CURRENT_DATE,
    PRIMARY KEY (student_id, term), -- owner's key + term
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE
);
 
-- ------------------------------------------------------------
-- MAJOR
--   One row per major
--   major_id : the major's ID (primary key); filled in automatically
--              (1, 2, 3, ...) if left out
--   name     : the major's name, like 'Computer Science' (UNIQUE: each name appears only once)
-- ------------------------------------------------------------
CREATE TABLE Major (
    major_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100) NOT NULL UNIQUE -- Alternate Key
);
 
-- ------------------------------------------------------------
-- SECTION: weak entity (owned by COURSE)
--   One offering of a course in one term, like CS157A Sec 07 in Fall 2026
--   course_id         : the course this section belongs to
--   term              : the term, like 'Fall 2026'
--   section_no        : the section number, like 7 for Sec 07
--                       section numbers repeat across courses and across terms
--                       (CS157A Sec 07 can run in Fall 2026 and again in
--                       Spring 2027), so the key is (course_id, term, section_no)
--   start_date        : first day of the section
--   end_date          : last day; can't be before start_date
--   capacity          : most students that can be enrolled
--   waitlist_capacity : most students that can be on the waitlist (default 0)
--   days              : meeting days in week order, M T W R F S (R = Thursday)
--   start_time        : class start time
--   end_time          : class end time; must be after start_time
--   location          : building and room like 'MQH 225'
--   instructor_id     : who teaches it; NULL means the instructor is TBA
--   An instructor can't teach two overlapping sections (trigger trg_section_instructor below)
--   ON DELETE:
--     course deleted     -> its sections are deleted too (CASCADE)
--     instructor deleted -> section goes back to TBA (SET NULL)
-- ------------------------------------------------------------
CREATE TABLE Section (
    course_id          VARCHAR(10) NOT NULL,
    term               VARCHAR(100) NOT NULL,
    section_no         INT NOT NULL,
    start_date         DATE NOT NULL,
    end_date           DATE NOT NULL,
    capacity           INT NOT NULL CHECK (capacity >= 0),
    waitlist_capacity  INT NOT NULL DEFAULT 0 CHECK (waitlist_capacity >= 0),
    days               VARCHAR(7) NOT NULL
                       CHECK (days ~ '^M?T?W?R?F?S?$' AND days <> ''),
    start_time         TIME NOT NULL,
    end_time           TIME NOT NULL,
    location           VARCHAR(50),
    instructor_id      INT,
    PRIMARY KEY (course_id, term, section_no), -- owner's key + term + section number
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE CASCADE,
    FOREIGN KEY (instructor_id) REFERENCES Instructor(instructor_id) ON DELETE SET NULL,
    CHECK (end_date >= start_date), -- term can't end before it starts
    CHECK (end_time > start_time)   -- class can't end before it starts
);
 
-- ------------------------------------------------------------
-- ENROLLMENT
--   One student in one section
--   enrollment_id : the enrollment's ID (primary key); filled in automatically
--   student_id    : the student who enrolled
--   course_id     : the course of the section
--   term          : the term of the section, like 'Fall 2026'
--   section_no    : the section number; (course_id, term, section_no)
--                   points to one Section
--   status        : 'enrolled' (new rows start here), 'dropped', or 'completed'
--   grade         : stays NULL until the course is completed
--   time_enrolled : when the student enrolled (filled in automatically)
--   (student_id, course_id, term, section_no) is UNIQUE: a student can
--   enroll in the same section only once (they can retake the course in
--   a later term, because that is a different section)
--   Seat limit (capacity) is checked by trigger trg_enrollment_capacity below
--   Unit limit per term is checked by trigger trg_enrollment_units below
--   Prerequisites are checked by trigger trg_enrollment_prereqs below
--   Schedule conflicts are checked by trigger trg_enrollment_schedule below
--   When a student drops, trg_waitlist_promote enrolls the next waitlisted student
--   ON DELETE: student or section deleted -> enrollment deleted (CASCADE)
-- ------------------------------------------------------------
CREATE TABLE Enrollment (
    enrollment_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id     INT NOT NULL,
    course_id      VARCHAR(10) NOT NULL,
    term           VARCHAR(100) NOT NULL,
    section_no     INT NOT NULL,
    status         VARCHAR(10) NOT NULL DEFAULT 'enrolled'
                   CHECK (status IN ('enrolled', 'dropped', 'completed')),
    grade          VARCHAR(2)
                   CHECK (grade IN ('A+','A','A-','B+','B','B-','C+','C','C-','D+','D','D-','F')),
    time_enrolled  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id, term, section_no) REFERENCES Section(course_id, term, section_no) ON DELETE CASCADE,
    UNIQUE (student_id, course_id, term, section_no), -- no double enrollment
    CHECK (grade IS NULL OR status = 'completed') -- only completed rows get a grade
);
 
-- ------------------------------------------------------------
-- WAITLIST
--   One student waiting for a seat in one section
--   waitlist_id : the waitlist entry's ID (primary key); filled in automatically
--   student_id  : the student who is waiting
--   course_id   : the course of the section
--   term        : the term of the section, like 'Fall 2026'
--   section_no  : the section number; (course_id, term, section_no) points to one Section
--   position    : place in line, 1 = next to get a seat
--   join_date   : when the student joined the waitlist (filled in automatically)
--   (student_id, course_id, term, section_no) is UNIQUE: a student is on a
--   section's waitlist only once
--   (course_id, term, section_no, position) is UNIQUE: no two students share
--   the same spot in line
--   The position rule is checked at COMMIT (DEFERRABLE), so everyone
--   can move up one spot inside a single transaction
--   Waitlist limit is checked by trigger trg_waitlist_capacity below
--   ON DELETE: student or section deleted -> waitlist row deleted (CASCADE)
-- ------------------------------------------------------------
CREATE TABLE Waitlist (
    waitlist_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id   INT NOT NULL,
    course_id    VARCHAR(10) NOT NULL,
    term         VARCHAR(100) NOT NULL,
    section_no   INT NOT NULL,
    position     INT NOT NULL CHECK (position >= 1),
    join_date    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id, term, section_no) REFERENCES Section(course_id, term, section_no) ON DELETE CASCADE,
    UNIQUE (student_id, course_id, term, section_no), -- on a waitlist only once
    UNIQUE (course_id, term, section_no, position)    -- one student per spot
        DEFERRABLE INITIALLY DEFERRED
);
 
-- ------------------------------------------------------------
-- TRANSFER_COURSE: ISA subtype of TRANSFER_CREDIT
--   A class taken at another school that counts for a course here
--   transfer_credit_id : the credit's ID (primary key); filled in automatically
--   grade              : the grade earned at the other school
--   student_id         : the student who earned the credit
--   course_id          : the course here it counts for
--   ON DELETE:
--     student deleted -> credit deleted (CASCADE)
--     course deleted  -> credit is kept, course_id becomes NULL (SET NULL)
-- ------------------------------------------------------------
CREATE TABLE Transfer_Course (
    transfer_credit_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade               VARCHAR(2) NOT NULL
                        CHECK (grade IN ('A+','A','A-','B+','B','B-','C+','C','C-','D+','D','D-','F')),
    student_id          INT NOT NULL,
    course_id           VARCHAR(10),
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE SET NULL
);
 
-- ------------------------------------------------------------
-- AP_CREDIT: ISA subtype of TRANSFER_CREDIT
--   An AP exam score that counts for a course here
--   transfer_credit_id : the credit's ID (primary key); filled in automatically
--   score              : the AP exam score, 1 to 5
--   student_id         : the student who took the exam
--   course_id          : the course here it counts for
--   ON DELETE: same as TRANSFER_COURSE (CASCADE / SET NULL)
-- ------------------------------------------------------------
CREATE TABLE AP_Credit (
    transfer_credit_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    score               INT NOT NULL CHECK (score BETWEEN 1 AND 5),
    student_id          INT NOT NULL,
    course_id           VARCHAR(10),
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE SET NULL
);
 
-- ------------------------------------------------------------
-- MAJOR_COURSE_OFFERING: many-to-many junction table
--   Which courses belong to which majors
--   One major has many courses; one course can be in many majors
--   major_id  : the major
--   course_id : a course in that major
--   (major_id, course_id) together is the key
--   ON DELETE: major or course deleted -> the link is deleted (CASCADE)
-- ------------------------------------------------------------
CREATE TABLE Major_Course_Offering (
    major_id   INT NOT NULL,
    course_id  VARCHAR(10) NOT NULL,
    PRIMARY KEY (major_id, course_id),
    FOREIGN KEY (major_id) REFERENCES Major(major_id) ON DELETE CASCADE,
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE CASCADE
);
 
-- ------------------------------------------------------------
-- STUDENT_MAJOR: many-to-many junction table
--   Which majors each student is in (a student can double major)
--   student_id : the student
--   major_id   : a major the student is in
--   (student_id, major_id) together is the key
--   ON DELETE:
--     student deleted -> the link is deleted (CASCADE)
--     major deleted   -> blocked while students are still in it (RESTRICT)
-- ------------------------------------------------------------
CREATE TABLE Student_Major (
    student_id  INT NOT NULL,
    major_id    INT NOT NULL,
    PRIMARY KEY (student_id, major_id),
    FOREIGN KEY (student_id) REFERENCES Student(student_id) ON DELETE CASCADE,
    FOREIGN KEY (major_id) REFERENCES Major(major_id) ON DELETE RESTRICT
);
 
-- ------------------------------------------------------------
-- COURSE_PREREQUISITE: recursive relationship (Course -> Course)
--   course_id        : the course that has the requirement
--   prereq_course_id : the course you have to take first
--                      (course_id, prereq_course_id) together is the key
--   min_grade        : lowest grade that still counts (default C-)
--   override         : TRUE if the requirement can be waived
--   A course can't be its own prerequisite
--   ON DELETE:
--     course deleted        -> its requirements are deleted (CASCADE)
--     prereq course deleted -> blocked while other courses need it (RESTRICT)
-- ------------------------------------------------------------
CREATE TABLE Course_Prerequisite (
    course_id         VARCHAR(10) NOT NULL,
    prereq_course_id  VARCHAR(10) NOT NULL,
    min_grade         VARCHAR(2) NOT NULL DEFAULT 'C-'
                      CHECK (min_grade IN ('A+','A','A-','B+','B','B-','C+','C','C-','D+','D','D-')),
    override          BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (course_id, prereq_course_id),
    FOREIGN KEY (course_id) REFERENCES Course(course_id) ON DELETE CASCADE,
    FOREIGN KEY (prereq_course_id) REFERENCES Course(course_id) ON DELETE RESTRICT,
    CHECK (course_id <> prereq_course_id)
);
 
-- ============================================================
-- TRIGGERS
--   These rules need to COUNT, ADD UP, or SEARCH many rows ("how many
--   students are already in this section?", "how many units is this
--   student taking this term?", "does this class overlap another one?");
--   a CHECK, UNIQUE, or FOREIGN KEY only
--   looks at one row or one key, so it can't do this, but a trigger can
-- ============================================================
 
-- ------------------------------------------------------------
-- trg_enrollment_capacity
--   Rule: a section can't have more 'enrolled' students than its capacity
--   Runs before a new enrollment, or before an update that could take
--   a seat (status changed to 'enrolled', or moved to another section)
--   If the section is full, the INSERT/UPDATE fails with an error
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_section_capacity() RETURNS TRIGGER AS $$
DECLARE
    sec_capacity  INT;
    seats_taken   INT;
BEGIN
    -- Dropped and completed rows don't take a seat, so let them through
    IF NEW.status <> 'enrolled' THEN
        RETURN NEW;
    END IF;
 
    -- Get the section's capacity and lock the section row, so if two
    -- students enroll at the same moment they are checked one at a time
    SELECT capacity INTO sec_capacity
    FROM Section
    WHERE course_id = NEW.course_id AND term = NEW.term AND section_no = NEW.section_no
    FOR UPDATE;
 
    -- Count the seats already taken (not counting this row itself)
    SELECT COUNT(*) INTO seats_taken
    FROM Enrollment
    WHERE course_id = NEW.course_id
      AND term = NEW.term
      AND section_no = NEW.section_no
      AND status = 'enrolled'
      AND enrollment_id <> NEW.enrollment_id;
 
    -- Full: stop with an error (code 23514 = check violation)
    IF seats_taken >= sec_capacity THEN
        RAISE EXCEPTION 'Section %-% (%) is full (% of % seats taken); join the waitlist instead',
            NEW.course_id, NEW.section_no, NEW.term, seats_taken, sec_capacity
            USING ERRCODE = 'check_violation';
    END IF;
 
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
 
CREATE TRIGGER trg_enrollment_capacity
BEFORE INSERT OR UPDATE OF status, course_id, term, section_no ON Enrollment
FOR EACH ROW EXECUTE FUNCTION check_section_capacity();
 
-- ------------------------------------------------------------
-- trg_waitlist_capacity
--   Rule: a section's waitlist can't have more students than its
--   waitlist_capacity; works the same way as the trigger above
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_waitlist_capacity() RETURNS TRIGGER AS $$
DECLARE
    wl_capacity  INT;
    wl_count     INT;
BEGIN
    -- Get the waitlist limit and lock the section row
    SELECT waitlist_capacity INTO wl_capacity
    FROM Section
    WHERE course_id = NEW.course_id AND term = NEW.term AND section_no = NEW.section_no
    FOR UPDATE;
 
    -- Count the students already waiting (not counting this row itself)
    SELECT COUNT(*) INTO wl_count
    FROM Waitlist
    WHERE course_id = NEW.course_id
      AND term = NEW.term
      AND section_no = NEW.section_no
      AND waitlist_id <> NEW.waitlist_id;
 
    -- Full: stop with an error
    IF wl_count >= wl_capacity THEN
        RAISE EXCEPTION 'Waitlist for section %-% (%) is full (% of % spots taken)',
            NEW.course_id, NEW.section_no, NEW.term, wl_count, wl_capacity
            USING ERRCODE = 'check_violation';
    END IF;
 
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
 
CREATE TRIGGER trg_waitlist_capacity
BEFORE INSERT OR UPDATE OF course_id, term, section_no ON Waitlist
FOR EACH ROW EXECUTE FUNCTION check_waitlist_capacity();
 
-- ------------------------------------------------------------
-- trg_enrollment_units
--   Rule: a student can't be enrolled in more than 18 units in one term,
--   unless they have an approved override in UNIT_OVERRIDE for that term
--   Adds up the units of every section the student is 'enrolled' in
--   for that term (same term, like 'Fall 2026'), plus the new
--   course; if the total is over the student's limit, the INSERT/UPDATE fails
--   Dropped and completed classes don't count
--   To change the normal limit for everyone, change default_max below
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_unit_limit() RETURNS TRIGGER AS $$
DECLARE
    default_max   CONSTANT INT := 18;
    max_units     INT;
    new_term      VARCHAR(100);
    new_units     INT;
    current_units INT;
BEGIN
    -- Dropped and completed rows don't count toward the limit
    IF NEW.status <> 'enrolled' THEN
        RETURN NEW;
    END IF;
 
    -- Lock the student's row, so if the same student enrolls in two
    -- classes at the same moment they are checked one at a time
    PERFORM 1 FROM Student WHERE student_id = NEW.student_id FOR UPDATE;
 
    -- The term and units of the section being added
    new_term := NEW.term;
    SELECT units INTO new_units FROM Course WHERE course_id = NEW.course_id;
 
    -- The student's limit for that term: their approved override if
    -- they have one, otherwise the normal limit
    SELECT COALESCE(
        (SELECT u.max_units FROM Unit_Override u
          WHERE u.student_id = NEW.student_id AND u.term = new_term),
        default_max) INTO max_units;
 
    -- Units the student already has that term (not counting this row itself)
    SELECT COALESCE(SUM(c.units), 0) INTO current_units
    FROM Enrollment e
    JOIN Course c ON c.course_id = e.course_id
    WHERE e.student_id = NEW.student_id
      AND e.status = 'enrolled'
      AND e.term = new_term
      AND e.enrollment_id <> NEW.enrollment_id;
 
    -- Over the limit: stop with an error
    IF current_units + new_units > max_units THEN
        RAISE EXCEPTION 'Unit limit reached: student % has % units in %; adding % would go over % units',
            NEW.student_id, current_units, new_term, new_units, max_units
            USING ERRCODE = 'check_violation';
    END IF;
 
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
 
CREATE TRIGGER trg_enrollment_units
BEFORE INSERT OR UPDATE OF status, course_id, term, section_no ON Enrollment
FOR EACH ROW EXECUTE FUNCTION check_unit_limit();
 
-- ------------------------------------------------------------
-- grade_points (helper function)
--   Turns a letter grade into a number (A+ = 4.3 ... F = 0) so grades
--   can be compared, like "is B+ at least C-?"
--   Used by the prerequisite trigger below
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION grade_points(g VARCHAR) RETURNS NUMERIC AS $$
    SELECT CASE g
        WHEN 'A+' THEN 4.3 WHEN 'A' THEN 4.0 WHEN 'A-' THEN 3.7
        WHEN 'B+' THEN 3.3 WHEN 'B' THEN 3.0 WHEN 'B-' THEN 2.7
        WHEN 'C+' THEN 2.3 WHEN 'C' THEN 2.0 WHEN 'C-' THEN 1.7
        WHEN 'D+' THEN 1.3 WHEN 'D' THEN 1.0 WHEN 'D-' THEN 0.7
        WHEN 'F'  THEN 0.0
    END;
$$ LANGUAGE sql IMMUTABLE;
 
-- ------------------------------------------------------------
-- trg_enrollment_prereqs
--   Rule: a student can't enroll in a course until they have passed
--   each of its prerequisites with at least min_grade
--   A prerequisite counts as passed if the student has any of:
--     a completed enrollment in it with grade >= min_grade
--     a transfer course for it with grade >= min_grade
--     an AP credit for it with score 3 or higher
--   Prerequisites with override = TRUE are skipped (they can be waived)
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_prereqs() RETURNS TRIGGER AS $$
DECLARE
    missing VARCHAR(10);
BEGIN
    -- Only check rows that take a seat
    IF NEW.status <> 'enrolled' THEN
        RETURN NEW;
    END IF;
 
    -- Find the first prerequisite the student has NOT passed
    SELECT p.prereq_course_id INTO missing
    FROM Course_Prerequisite p
    WHERE p.course_id = NEW.course_id
      AND p.override = FALSE
      AND NOT EXISTS (SELECT 1 FROM Enrollment e
                       WHERE e.student_id = NEW.student_id
                         AND e.course_id = p.prereq_course_id
                         AND e.status = 'completed'
                         AND grade_points(e.grade) >= grade_points(p.min_grade))
      AND NOT EXISTS (SELECT 1 FROM Transfer_Course t
                       WHERE t.student_id = NEW.student_id
                         AND t.course_id = p.prereq_course_id
                         AND grade_points(t.grade) >= grade_points(p.min_grade))
      AND NOT EXISTS (SELECT 1 FROM AP_Credit a
                       WHERE a.student_id = NEW.student_id
                         AND a.course_id = p.prereq_course_id
                         AND a.score >= 3)
    LIMIT 1;
 
    -- A prerequisite is missing: stop with an error
    IF missing IS NOT NULL THEN
        RAISE EXCEPTION 'Prerequisite not met: student % needs % before %',
            NEW.student_id, missing, NEW.course_id
            USING ERRCODE = 'check_violation';
    END IF;
 
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
 
CREATE TRIGGER trg_enrollment_prereqs
BEFORE INSERT OR UPDATE OF status, course_id ON Enrollment
FOR EACH ROW EXECUTE FUNCTION check_prereqs();
 
-- ------------------------------------------------------------
-- trg_enrollment_schedule
--   Rule: a student can't be enrolled in two sections that meet at the
--   same time in the same term
--   Two sections conflict if they share a meeting day (like both on M)
--   AND their times overlap (one starts before the other ends)
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_student_schedule() RETURNS TRIGGER AS $$
DECLARE
    clash_course VARCHAR(10);
    clash_sec    INT;
BEGIN
    -- Only check rows that take a seat
    IF NEW.status <> 'enrolled' THEN
        RETURN NEW;
    END IF;
 
    -- Look for another class this student is enrolled in that overlaps
    SELECT other.course_id, other.section_no INTO clash_course, clash_sec
    FROM Section new_sec
    JOIN Enrollment e  ON e.student_id = NEW.student_id
                      AND e.term = NEW.term
                      AND e.status = 'enrolled'
                      AND e.enrollment_id <> NEW.enrollment_id
    JOIN Section other ON other.course_id = e.course_id
                      AND other.term = e.term
                      AND other.section_no = e.section_no
    WHERE new_sec.course_id = NEW.course_id
      AND new_sec.term = NEW.term
      AND new_sec.section_no = NEW.section_no
      AND other.days ~ ('[' || new_sec.days || ']')   -- share a day
      AND new_sec.start_time < other.end_time          -- times overlap
      AND other.start_time < new_sec.end_time
    LIMIT 1;
 
    -- Found one: stop with an error
    IF clash_course IS NOT NULL THEN
        RAISE EXCEPTION 'Schedule conflict: %-% overlaps with %-% that student % is already in',
            NEW.course_id, NEW.section_no, clash_course, clash_sec, NEW.student_id
            USING ERRCODE = 'check_violation';
    END IF;
 
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
 
CREATE TRIGGER trg_enrollment_schedule
BEFORE INSERT OR UPDATE OF status, course_id, term, section_no ON Enrollment
FOR EACH ROW EXECUTE FUNCTION check_student_schedule();
 
-- ------------------------------------------------------------
-- trg_section_instructor
--   Rule: an instructor can't teach two sections that meet at the same
--   time in the same term (same day + overlapping times)
--   TBA sections (instructor_id NULL) are not checked
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION check_instructor_schedule() RETURNS TRIGGER AS $$
DECLARE
    clash_course VARCHAR(10);
    clash_sec    INT;
BEGIN
    IF NEW.instructor_id IS NULL THEN
        RETURN NEW;
    END IF;
 
    -- Look for another section this instructor teaches that overlaps
    SELECT s.course_id, s.section_no INTO clash_course, clash_sec
    FROM Section s
    WHERE s.instructor_id = NEW.instructor_id
      AND s.term = NEW.term
      AND NOT (s.course_id = NEW.course_id AND s.section_no = NEW.section_no)
      AND s.days ~ ('[' || NEW.days || ']')   -- share a day
      AND s.start_time < NEW.end_time         -- times overlap
      AND NEW.start_time < s.end_time
    LIMIT 1;
 
    -- Found one: stop with an error
    IF clash_course IS NOT NULL THEN
        RAISE EXCEPTION 'Instructor % is already teaching %-% at that time in %',
            NEW.instructor_id, clash_course, clash_sec, NEW.term
            USING ERRCODE = 'check_violation';
    END IF;
 
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
 
CREATE TRIGGER trg_section_instructor
BEFORE INSERT OR UPDATE OF instructor_id, term, days, start_time, end_time ON Section
FOR EACH ROW EXECUTE FUNCTION check_instructor_schedule();
 
-- ------------------------------------------------------------
-- trg_waitlist_promote
--   Rule: when an enrolled student drops (status changes from 'enrolled'
--   to something else), the next student on that section's waitlist is
--   enrolled automatically, removed from the waitlist, and everyone
--   behind them moves up one spot
--   Runs AFTER the drop is saved
--   If the next student can't be enrolled (example: over their unit
--   limit, or a schedule conflict), they are skipped and stay on the
--   waitlist, and the student after them is tried
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION promote_from_waitlist() RETURNS TRIGGER AS $$
DECLARE
    w RECORD;
BEGIN
    -- Only when a seat is given up
    IF OLD.status <> 'enrolled' OR NEW.status = 'enrolled' THEN
        RETURN NULL;
    END IF;
 
    -- Try waitlisted students in order of position (1 first)
    FOR w IN
        SELECT waitlist_id, student_id, position
        FROM Waitlist
        WHERE course_id = OLD.course_id AND term = OLD.term AND section_no = OLD.section_no
        ORDER BY position
    LOOP
        BEGIN
            -- Enroll them (all the enrollment triggers still check this)
            INSERT INTO Enrollment (student_id, course_id, term, section_no)
            VALUES (w.student_id, OLD.course_id, OLD.term, OLD.section_no);
 
            -- Take them off the waitlist and move everyone behind them up
            DELETE FROM Waitlist WHERE waitlist_id = w.waitlist_id;
            UPDATE Waitlist SET position = position - 1
            WHERE course_id = OLD.course_id AND term = OLD.term
              AND section_no = OLD.section_no AND position > w.position;
 
            EXIT; -- one seat opened, one student promoted
        EXCEPTION WHEN check_violation OR unique_violation THEN
            -- This student can't take the seat; try the next one
            CONTINUE;
        END;
    END LOOP;
 
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;
 
CREATE TRIGGER trg_waitlist_promote
AFTER UPDATE OF status ON Enrollment
FOR EACH ROW EXECUTE FUNCTION promote_from_waitlist();
 
-- ============================================================
-- VIEW: Section_Seat_Status
--   One row per section showing when it meets, capacity, students enrolled, seats
--   open, and waitlist size; the counts are worked out every time you
--   query the view, so they are always up to date; we don't store them
--   as columns in Section, because a stored count could get out of sync
--   with the Enrollment table
--   LEFT JOIN on Instructor keeps sections with no instructor (shown as TBA)
-- ============================================================
CREATE OR REPLACE VIEW Section_Seat_Status AS
SELECT
    s.course_id,
    s.term,
    s.section_no,
    c.name AS course_name,
    COALESCE(i.first_name || ' ' || i.last_name, 'TBA') AS instructor,
    s.days,
    s.start_time,
    s.end_time,
    s.capacity,
    (SELECT COUNT(*) FROM Enrollment e
      WHERE e.course_id = s.course_id AND e.term = s.term AND e.section_no = s.section_no
        AND e.status = 'enrolled') AS enrolled_count,
    s.capacity - (SELECT COUNT(*) FROM Enrollment e
      WHERE e.course_id = s.course_id AND e.term = s.term AND e.section_no = s.section_no
        AND e.status = 'enrolled') AS seats_open,
    s.waitlist_capacity,
    (SELECT COUNT(*) FROM Waitlist w
      WHERE w.course_id = s.course_id AND w.term = s.term AND w.section_no = s.section_no) AS waitlist_count
FROM Section s
JOIN Course c ON c.course_id = s.course_id
LEFT JOIN Instructor i ON i.instructor_id = s.instructor_id;
